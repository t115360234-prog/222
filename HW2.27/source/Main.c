#include <stdio.h>

int main() {
    // 使用 5 個 printf 指令
    printf("    *    \n");
    printf("   ***   \n");
    printf("  *****  \n");
    printf(" ******* \n");
    printf("*********\n\n");

    // 只使用 1 個 printf 指令 (利用 \n 換行)
    printf("    *    \n   ***   \n  *****  \n ******* \n*********\n");

    return 0;
}